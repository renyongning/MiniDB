-- Self-contained teaching dataset: run once in a NEW database.
CREATE TABLE person(id INTEGER, name VARCHAR(20), born DATE);
CREATE TABLE visit(id INTEGER, name VARCHAR(20), born DATE);
CREATE TABLE area(id INTEGER, city VARCHAR(20));
INSERT INTO person VALUES (1,'Alice','2000-01-01'),(2,'Bob','2001-02-03'),(3,'Alice','2000-01-01'),(NULL,NULL,NULL);
INSERT INTO visit VALUES (1,'Alice','2000-01-01'),(1,'Alice','2000-01-01'),(2,'Bob','2001-02-03'),(4,'Carol','2002-03-04');
INSERT INTO area VALUES (1,'Beijing'),(2,'Shanghai'),(3,'Shenzhen');
CREATE INDEX visit_id ON visit(id);
CREATE INDEX visit_name ON visit(name);
CREATE INDEX visit_born ON visit(born);
CREATE INDEX area_id ON area(id);
PRAGMA scan_method=table;
SELECT id,name,born FROM person WHERE id BETWEEN 1 AND 3 AND name!='Bob';
PRAGMA scan_method=index;
SELECT * FROM visit WHERE born >= DATE '2000-01-01' AND born < DATE '2002-01-01';
PRAGMA scan_method=auto;
PRAGMA join_algorithm=nested_loop;
SELECT p.id,v.id FROM person p,visit v WHERE p.id=v.id;
PRAGMA join_algorithm=sort_merge;
SELECT p.id,v.id FROM person p,visit v WHERE p.id=v.id;
PRAGMA join_algorithm=hash;
SELECT p.id,v.id FROM person p,visit v WHERE p.id=v.id;
SELECT p.id,v.id FROM person p,visit v WHERE p.id=v.id AND p.name=v.name;
PRAGMA join_algorithm=index;
SELECT p.id,v.id FROM person p,visit v WHERE p.id=v.id;
SELECT p.name,v.name FROM person p,visit v WHERE p.name!=v.name;
SELECT p.born,v.born FROM person p,visit v WHERE p.born<v.born;
SELECT p.id,v.id FROM person p CROSS JOIN visit v LIMIT 6;
SELECT p.name,v.born,a.city FROM person p JOIN visit v ON p.id=v.id JOIN area a ON v.id=a.id;
EXPLAIN SELECT p.name,v.born,a.city FROM person p,visit v,area a WHERE p.id=v.id AND v.id=a.id;
